'use strict';
// Builds the Davening-only Functions codebase for the STAGING project
// (fun-torah-tools-staging), so the Chazzan feature (issue #799) and the
// Chayus Meter (issue #802) can be tested with the fictional accounts.
//
// The code is copied straight from backend/functions, so staging runs exactly
// the Davening code in this checkout. Only the deployment settings differ:
//   - the ET page uses fictional class TEST-ALEF and the WT page TEST-BEIS;
//   - the fictional password teachers (b3StagingAccount) are accepted;
//   - only the staging site and its Davening preview channel may call it.
// Every setting is off unless the code is running in the staging project.
// Output goes to an ignored folder that firebase.staging-davening.json deploys
// as its own codebase, so the existing staging functions are untouched.
//
// Usage: node staging/build-davening-functions.cjs [output-dir]

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = path.join(ROOT, 'backend', 'functions');
const DEFAULT_OUT = path.join(ROOT, '.staging-davening');
const STAGING_PROJECT = 'fun-torah-tools-staging';
const STAGING_ORIGIN = 'https://fun-torah-tools-staging.web.app';
const PREVIEW_CHANNEL = 'davening-799';
const CLASS_MAP = { et: 'TEST-ALEF', wt: 'TEST-BEIS' };
const FUNCTIONS = { daveningChazzan: './davening-chazzan', daveningChayus: './chayus-meter' };
const COPIED = [
  'davening-chazzan.js', 'chayus-meter.js', 'davening-session-auth.cjs', 'davening-session-core.cjs',
  'davening-session-service.cjs', 'chayus-session-service.cjs', 'chayus-report-core.cjs',
  'rewards-teacher-core.cjs', 'student-practice-auth.cjs'
];

function fail(message) { throw new Error('build-davening-functions: ' + message); }

function deploymentSource() {
  return [
    "'use strict';",
    '// GENERATED by staging/build-davening-functions.cjs. Staging only; do not edit.',
    '// Outside the staging project every setting is empty, so all requests are refused.',
    'const staging = process.env.GCLOUD_PROJECT === ' + JSON.stringify(STAGING_PROJECT) + ';',
    'module.exports = Object.freeze({',
    '  classMap: Object.freeze(staging ? ' + JSON.stringify(CLASS_MAP) + ' : {}),',
    '  stagingPasswordTeachers: staging,',
    '  cors: Object.freeze([' + JSON.stringify(STAGING_ORIGIN) + ',',
    '    new RegExp(' + JSON.stringify('^https://fun-torah-tools-staging--' + PREVIEW_CHANNEL + '-[a-z0-9]+[.]web[.]app$') + ')])',
    '});',
    ''
  ].join('\n');
}

function indexSource() {
  return "'use strict';\n// GENERATED by staging/build-davening-functions.cjs. Staging only; do not edit.\n" +
    Object.entries(FUNCTIONS).map(([name, file]) =>
      'exports.' + name + ' = require(' + JSON.stringify(file) + ').' + name + ';').join('\n') + '\n';
}

function build(outDir = DEFAULT_OUT) {
  const out = path.resolve(outDir);
  if (out === ROOT || out === SOURCE || !path.basename(out)) fail('refusing to write to ' + out);
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(out, { recursive: true });
  for (const name of COPIED) {
    const source = fs.readFileSync(path.join(SOURCE, name), 'utf8');
    // A copied file may only load Node built-ins, the two Firebase packages or another copied file.
    for (const [, wanted] of source.matchAll(/require\(\s*['"]([^'"]+)['"]\s*\)/g)) {
      const local = wanted.startsWith('./') ? wanted.slice(2).replace(/^(.*?)(\.c?js)?$/, (all, base, ext) => base + (ext || '.js')) : null;
      const allowed = wanted.startsWith('node:') || wanted === 'firebase-admin' || wanted.startsWith('firebase-functions')
        || (local && (COPIED.includes(local) || local === 'davening-deployment.cjs'));
      if (!allowed) fail(name + ' needs ' + wanted + ', which is not part of the Davening staging build');
    }
    fs.writeFileSync(path.join(out, name), source);
  }
  fs.writeFileSync(path.join(out, 'davening-deployment.cjs'), deploymentSource());
  fs.writeFileSync(path.join(out, 'index.js'), indexSource());
  // The small staging package: only firebase-admin and firebase-functions.
  for (const name of ['package.json', 'package-lock.json']) {
    fs.copyFileSync(path.join(ROOT, 'backend', 'functions-staging', name), path.join(out, name));
  }
  return { out, functions: Object.keys(FUNCTIONS) };
}

module.exports = { build, deploymentSource, indexSource, CLASS_MAP, COPIED, FUNCTIONS, PREVIEW_CHANNEL, STAGING_ORIGIN, STAGING_PROJECT };

if (require.main === module) {
  const result = build(process.argv[2]);
  console.log('Built ' + result.functions.join(', ') + ' into ' + result.out);
}
