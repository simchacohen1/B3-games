'use strict';
// Builds the grading-only Functions codebase for the STAGING project
// (fun-torah-tools-staging), so Pasuk Practice grading changes can be tested
// before they go live. Issue #107.
//
// The code comes straight from backend/functions/index.js, so staging runs
// exactly the grading code in this checkout. Only these functions are kept:
// every other production function is cut off or removed. CORS allows only the
// staging site. Output goes to an ignored folder that firebase.staging-posuk-grading.json
// deploys as its own codebase, so the existing staging functions are untouched.
//
// Usage: node staging/build-posuk-grading-functions.cjs [output-dir]

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = path.join(ROOT, 'backend', 'functions');
const DEFAULT_OUT = path.join(ROOT, '.staging-posuk-grading');
const STAGING_ORIGIN = 'https://fun-torah-tools-staging.web.app';

const KEEP = [
  'generateTranslationChunks',
  'gradeTranslationChunk',
  'gradeComprehension',
  'generateComprehensionQuestions',
  'gradeQuestionAnswer'
];
// Production functions defined in the kept part of index.js but not needed here.
const DROP = ['searchSefariaQuestions', 'synthesizeSpeech'];
// The grading functions are all defined above this line; everything after it
// is unrelated production code (weekly quiz, rewards, gallery, homework...).
const CUT_MARKER = 'exports.generateWeeklyQuiz = onRequest(';
const HELPERS = ['paid-api-core.cjs', 'student-passcodes.cjs', 'question-answer-spans.cjs', 'posuk-answer-grading.cjs'];

function fail(message) { throw new Error('build-posuk-grading-functions: ' + message); }

function buildIndex(source) {
  const cut = source.indexOf('\n' + CUT_MARKER);
  if (cut < 0) fail('cut marker not found: ' + CUT_MARKER);
  const head = source.slice(0, cut + 1);
  for (const name of [...KEEP, ...DROP]) {
    if (!head.includes('exports.' + name + ' = onRequest(')) fail('expected function missing from index.js: ' + name);
  }
  const defined = [...head.matchAll(/^exports\.(\w+)\s*=/gm)].map(m => m[1]);
  const unexpected = defined.filter(name => !KEEP.includes(name) && !DROP.includes(name));
  if (unexpected.length) fail('new function(s) above the cut, decide keep or drop: ' + unexpected.join(', '));
  return '// GENERATED by staging/build-posuk-grading-functions.cjs from backend/functions/index.js.\n' +
    '// Staging only (fun-torah-tools-staging). Do not edit; rebuild instead.\n' +
    head +
    '\n// Staging: deploy only the Pasuk Practice grading functions.\n' +
    DROP.map(name => 'delete exports.' + name + ';').join('\n') + '\n';
}

function buildPaidApi(source) {
  const pattern = /const ALLOWED_ORIGINS = \[[^\]]*\];/;
  if (!pattern.test(source)) fail('ALLOWED_ORIGINS not found in paid-api.js');
  return source.replace(pattern, 'const ALLOWED_ORIGINS = [' + JSON.stringify(STAGING_ORIGIN) + ']; // staging only');
}

function build(outDir = DEFAULT_OUT) {
  const out = path.resolve(outDir);
  if (out === ROOT || out === SOURCE || !path.basename(out)) fail('refusing to write to ' + out);
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(out, { recursive: true });
  const read = name => fs.readFileSync(path.join(SOURCE, name), 'utf8');
  fs.writeFileSync(path.join(out, 'index.js'), buildIndex(read('index.js')));
  fs.writeFileSync(path.join(out, 'paid-api.js'), buildPaidApi(read('paid-api.js')));
  for (const name of [...HELPERS, 'package.json', 'package-lock.json']) {
    fs.copyFileSync(path.join(SOURCE, name), path.join(out, name));
  }
  return { out, functions: KEEP.slice() };
}

module.exports = { build, buildIndex, buildPaidApi, KEEP, DROP, STAGING_ORIGIN };

if (require.main === module) {
  const result = build(process.argv[2]);
  console.log('Built ' + result.functions.join(', ') + ' into ' + result.out);
}
