'use strict';
// Turns the hand-written lists of section NUMBERS (tools/region-groups-source.json,
// numbers as printed by section-sheet.cjs) into region-groups.js, which stores
// plain seed points instead. Seeds keep working even if numbering changes later.
//   FTT_CANVAS_MODULE=... node sefer-hamitzvos/tools/build-region-groups.cjs
// A source group is {name, sections:[numbers]} (merge these) or
// {name, seed:[x,y], within:'outline', keep:[numbers]} (everything inside one thick outline).
const fs=require('fs'),path=require('path');
const {createCanvas,loadImage}=require(process.env.FTT_CANVAS_MODULE||'@napi-rs/canvas');
const F=require('../fill.js'),root=path.resolve(__dirname,'..');
(async()=>{
 const source=JSON.parse(fs.readFileSync(path.join(__dirname,'region-groups-source.json'),'utf8')),out={};
 for(const [card,groups] of Object.entries(source)){
  const im=await loadImage(path.join(root,'coloring-v2',card+'.png')),c=createCanvas(im.width,im.height),x=c.getContext('2d');x.drawImage(im,0,0);
  // Numbers are those of the engine WITHOUT groups, exactly what section-sheet.cjs shows.
  const m=F.createObjectMask(x.getImageData(0,0,im.width,im.height),im.width,im.height,[]);
  const centre=new Map();
  for(let i=0;i<m.labels.length;i++){const l=m.labels[i];if(!l)continue;let e=centre.get(l);if(!e){e={n:0,sx:0,sy:0};centre.set(l,e)}e.n++;e.sx+=i%im.width;e.sy+=(i/im.width)|0;}
  const seed=new Map();
  for(const [l,e] of centre)seed.set(l,{cx:e.sx/e.n,cy:e.sy/e.n,d:1e18,p:null});
  for(let i=0;i<m.labels.length;i++){const l=m.labels[i];if(!l)continue;const s=seed.get(l),px=i%im.width,py=(i/im.width)|0,d=(px-s.cx)**2+(py-s.cy)**2;if(d<s.d){s.d=d;s.p=[px,py];}}
  const at=n=>{const s=seed.get(Number(n));if(!s)throw new Error(`card ${card}: no section ${n}`);return s.p;};
  for(const g of groups){const area=(g.sections||[]).reduce((a,n)=>a+centre.get(Number(n)).n,0),pct=100*area/m.labels.length;if(pct>6)console.warn(`WARNING card ${card} "${g.name}" covers ${pct.toFixed(1)}% of the picture; is a background section included by mistake?`);}
  out[card]=groups.map(g=>g.within?{name:g.name,seed:g.seed,within:'outline',keep:(g.keep||[]).map(at)}:{name:g.name,join:g.sections.map(at)});
 }
 const lines=Object.entries(out).map(([card,g])=>` ${JSON.stringify(card)}:${JSON.stringify(g)}`);
 fs.writeFileSync(path.join(root,'region-groups.js'),'// Generated by tools/build-region-groups.cjs from tools/region-groups-source.json.\r\n// Which sections are ONE object (pants, sleeves, hands, faces...). Seed points are native-picture pixels.\r\n(function(){window.FTT_SEFER_REGION_GROUPS={\r\n'+lines.join(',\r\n')+'\r\n};})();\r\n');
 console.log('wrote groups for',Object.keys(out).join(', '));
})();
